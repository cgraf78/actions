#!/usr/bin/env bash

set -euo pipefail

usage() {
  cat >&2 <<'EOF'
usage: checkout-installer/render.sh [--check] <consumer-repository>

Generate the consumer's self-contained top-level install.sh from
scripts/checkout-installer.conf. The config must set
CHECKOUT_INSTALLER_ENABLED=true.

--check renders to a temporary file and fails if the committed installer differs.
EOF
}

die() {
  printf 'checkout-installer-render: %s\n' "$*" >&2
  exit 1
}

check=false
case $#:${1:-} in
  1:*) ;;
  2:--check)
    check=true
    shift
    ;;
  *)
    usage
    exit 2
    ;;
esac

source_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
template="$source_dir/install.sh.in"
lock_v1_fragment="$source_dir/lock-v1.sh.in"
bash_resolver_fragment="$source_dir/bash-resolver-v1.sh.in"
consumer=$1
config="$consumer/scripts/checkout-installer.conf"
output="$consumer/install.sh"
generated_header='# Generated by cgraf78/actions checkout-installer. Do not edit.'
bash_resolver_output="$consumer/support/checkout-bash-v1.sh"
bash_resolver_header='# Generated by cgraf78/actions checkout Bash resolver. Do not edit.'
bash_resolver_output_owned=false
output_owned=false

bash_resolver_parent_kind() {
  local parent=$consumer/support

  if [[ ! -e "$parent" && ! -L "$parent" ]]; then
    printf 'missing\n'
  elif [[ -d "$parent" && ! -L "$parent" ]]; then
    printf 'directory\n'
  else
    printf 'unsafe\n'
  fi
}

[[ -d "$consumer" && ! -L "$consumer" ]] ||
  die "consumer repository must be a regular directory: $consumer"
[[ -f "$config" && ! -L "$config" ]] ||
  die "checkout installer config must be a regular file: $config"
[[ -f "$template" && ! -L "$template" ]] ||
  die "installer template must be a regular file: $template"

# Clear every input before sourcing the consumer policy. A maintainer's shell
# environment must not silently alter generated, committed installer bytes.
CHECKOUT_INSTALLER_ENABLED=
CHECKOUT_INSTALLER_REPO=
CHECKOUT_INSTALLER_REF=
CHECKOUT_INSTALLER_DELEGATE=
CHECKOUT_INSTALLER_DEFAULT_DESTINATION=
CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE=
CHECKOUT_INSTALLER_LOCK_PROTOCOL=
CHECKOUT_INSTALLER_BASH_RESOLVER=
CHECKOUT_INSTALLER_DEVELOPMENT_POLICY=

# shellcheck source=/dev/null
. "$config"

if [[ ${CHECKOUT_INSTALLER_ENABLED:-} != true ]]; then
  disabled_removed=false
  if [[ -f "$output" && ! -L "$output" &&
    $(sed -n '2p' "$output") == "$generated_header" ]]; then
    if [[ "$check" == true ]]; then
      die "generated installer remains while checkout installer policy is disabled: $output"
    fi
    rm -f "$output"
    printf 'checkout-installer-render: removed disabled generated installer %s\n' \
      "$output"
    disabled_removed=true
  fi
  bash_resolver_parent=$(bash_resolver_parent_kind)
  if [[ "$bash_resolver_parent" == directory &&
    -f "$bash_resolver_output" && ! -L "$bash_resolver_output" &&
    $(sed -n '2p' "$bash_resolver_output") == "$bash_resolver_header" ]]; then
    if [[ "$check" == true ]]; then
      die "generated Bash resolver remains while checkout installer policy is disabled: $bash_resolver_output"
    fi
    rm -f "$bash_resolver_output"
    printf 'checkout-installer-render: removed disabled generated Bash resolver %s\n' \
      "$bash_resolver_output"
    disabled_removed=true
  fi
  if [[ "$disabled_removed" != true ]]; then
    printf 'checkout-installer-render: checkout installer is not enabled in %s\n' \
      "$config"
  fi
  exit 0
fi

[[ ${CHECKOUT_INSTALLER_REPO:-} =~ ^[A-Za-z0-9._-]+/[A-Za-z0-9._-]+$ ]] ||
  die 'CHECKOUT_INSTALLER_REPO must be an owner/repository name'

checkout_owner=${CHECKOUT_INSTALLER_REPO%%/*}
checkout_slug=${CHECKOUT_INSTALLER_REPO##*/}
for name in "$checkout_owner" "$checkout_slug"; do
  [[ "$name" != . && "$name" != .. ]] ||
    die 'CHECKOUT_INSTALLER_REPO must not contain dot segments'
done
: "${CHECKOUT_INSTALLER_REF:=main}"
: "${CHECKOUT_INSTALLER_DELEGATE:=support/install-checkout.sh}"
: "${CHECKOUT_INSTALLER_DEFAULT_DESTINATION:=xdg}"
: "${CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE:=}"
: "${CHECKOUT_INSTALLER_LOCK_PROTOCOL:=}"
: "${CHECKOUT_INSTALLER_BASH_RESOLVER:=}"
: "${CHECKOUT_INSTALLER_DEVELOPMENT_POLICY:=}"

case "$CHECKOUT_INSTALLER_REF" in
  '' | -* | /* | */ | *//* | *..* | *[!A-Za-z0-9._/-]*)
    die 'CHECKOUT_INSTALLER_REF must be a safe branch name'
    ;;
esac
case "$CHECKOUT_INSTALLER_DELEGATE" in
  '' | -* | . | .. | /* | ./* | */./* | */. | *[!A-Za-z0-9._/-]* | *//* | ../* | */../* | */..)
    die 'CHECKOUT_INSTALLER_DELEGATE must be a safe relative path'
    ;;
esac
[[ "$CHECKOUT_INSTALLER_DELEGATE" != install.sh ]] ||
  die 'CHECKOUT_INSTALLER_DELEGATE must not be install.sh'
if [[ -n "$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE" ]]; then
  case "$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE" in
    -* | . | .. | /* | ./* | */./* | */. | *[!A-Za-z0-9._/-]* | *//* | ../* | */../* | */..)
      die 'CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE must be a safe relative path'
      ;;
  esac
  [[ "$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE" != install.sh ]] ||
    die 'CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE must not be install.sh'
  [[ "$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE" != "$CHECKOUT_INSTALLER_DELEGATE" ]] ||
    die 'CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE must differ from CHECKOUT_INSTALLER_DELEGATE'
fi
case "$CHECKOUT_INSTALLER_DEFAULT_DESTINATION" in
  xdg | shdeps) ;;
  *)
    die 'CHECKOUT_INSTALLER_DEFAULT_DESTINATION must be xdg or shdeps'
    ;;
esac
case "$CHECKOUT_INSTALLER_LOCK_PROTOCOL" in
  '' | v1) ;;
  *)
    die 'CHECKOUT_INSTALLER_LOCK_PROTOCOL must be v1 when set'
    ;;
esac
case "$CHECKOUT_INSTALLER_BASH_RESOLVER" in
  '' | v1) ;;
  *)
    die 'CHECKOUT_INSTALLER_BASH_RESOLVER must be v1 when set'
    ;;
esac
case "$CHECKOUT_INSTALLER_DEVELOPMENT_POLICY" in
  '' | shdeps) ;;
  *)
    die 'CHECKOUT_INSTALLER_DEVELOPMENT_POLICY must be shdeps when set'
    ;;
esac
if [[ "$CHECKOUT_INSTALLER_DEVELOPMENT_POLICY" == shdeps ]]; then
  [[ "$CHECKOUT_INSTALLER_DEFAULT_DESTINATION" == shdeps ]] ||
    die 'Shdeps development policy requires CHECKOUT_INSTALLER_DEFAULT_DESTINATION=shdeps'
  [[ "$CHECKOUT_INSTALLER_LOCK_PROTOCOL" == v1 ]] ||
    die 'Shdeps development policy requires CHECKOUT_INSTALLER_LOCK_PROTOCOL=v1'
fi

delegate="$consumer/$CHECKOUT_INSTALLER_DELEGATE"
[[ -f "$delegate" && ! -L "$delegate" ]] ||
  die "checkout installer delegate must be a regular file: $delegate"
if [[ -n "$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE" ]]; then
  post_install="$consumer/$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE"
  [[ -f "$post_install" && ! -L "$post_install" ]] ||
    die "checkout installer post-install command must be a regular file: $post_install"
fi
if [[ "$check" != true && (-e "$output" || -L "$output") ]]; then
  [[ -f "$output" && ! -L "$output" &&
    $(sed -n '2p' "$output") == "$generated_header" ]] ||
    die "refusing to overwrite consumer-owned installer: $output"
  output_owned=true
fi
if [[ "$CHECKOUT_INSTALLER_BASH_RESOLVER" == v1 ]]; then
  [[ -f "$bash_resolver_fragment" && ! -L "$bash_resolver_fragment" ]] ||
    die "checkout Bash resolver fragment must be a regular file: $bash_resolver_fragment"
  bash_resolver_parent=$(bash_resolver_parent_kind)
  if [[ "$bash_resolver_parent" != missing ]]; then
    [[ "$bash_resolver_parent" == directory ]] ||
      die "checkout Bash resolver parent must be a regular directory: $consumer/support"
  elif [[ "$check" == true ]]; then
    die "generated Bash resolver parent is missing: $consumer/support"
  else
    mkdir -p "$consumer/support"
  fi
  if [[ -e "$bash_resolver_output" || -L "$bash_resolver_output" ]]; then
    [[ -f "$bash_resolver_output" && ! -L "$bash_resolver_output" &&
      $(sed -n '2p' "$bash_resolver_output") == "$bash_resolver_header" ]] ||
      die "refusing to overwrite consumer-owned Bash resolver: $bash_resolver_output"
    bash_resolver_output_owned=true
  fi
fi

tmp=
bash_resolver_tmp=
cleanup_render_temps() {
  [[ -z "$tmp" ]] || rm -f "$tmp"
  [[ -z "$bash_resolver_tmp" ]] || rm -f "$bash_resolver_tmp"
}
trap cleanup_render_temps EXIT

tmp=$(mktemp "$consumer/.install.sh.XXXXXX")
if [[ "$CHECKOUT_INSTALLER_BASH_RESOLVER" == v1 ]]; then
  bash_resolver_tmp=$(mktemp "$consumer/support/.checkout-bash-v1.sh.XXXXXX")
  {
    printf '#!/usr/bin/env bash\n%s\n' "$bash_resolver_header"
    while IFS= read -r fragment_line || [[ -n "$fragment_line" ]]; do
      printf '%s\n' "$fragment_line"
    done <"$bash_resolver_fragment"
  } >"$bash_resolver_tmp"
  chmod 0644 "$bash_resolver_tmp"
fi

# Literal generated shell expressions must be written without expanding the
# renderer's own variables.
# shellcheck disable=SC2016
emit_bash_invocation() {
  local marker=$1 indent=$2 managed_root='$checkout_dir'

  if [[ "$CHECKOUT_INSTALLER_DEVELOPMENT_POLICY" == shdeps ]]; then
    managed_root='$checkout_runtime_root'
  fi

  if [[ "$CHECKOUT_INSTALLER_BASH_RESOLVER" != v1 ]]; then
    case "$marker" in
      CHECKOUT_BASH_EXEC_ROOT_DELEGATE)
        printf '%sexec "$BASH" "$checkout_root/$checkout_delegate" "$@"\n' "$indent"
        ;;
      CHECKOUT_BASH_RUN_ROOT_DELEGATE)
        printf '%s"$BASH" "$checkout_root/$checkout_delegate" "$@" <&0 &\n' "$indent"
        ;;
      CHECKOUT_BASH_EXEC_ROOT_POST)
        printf '%sexec "$BASH" "$checkout_root/$checkout_post_install_delegate" "$@"\n' "$indent"
        ;;
      CHECKOUT_BASH_RUN_DIR_DELEGATE)
        printf '%s"$BASH" "%s/$checkout_delegate" "$@" <&0 &\n' \
          "$indent" "$managed_root"
        ;;
      CHECKOUT_BASH_EXEC_DIR_POST)
        printf '%sexec "$BASH" "%s/$checkout_post_install_delegate" "$@"\n' \
          "$indent" "$managed_root"
        ;;
      *) die "unknown Bash invocation marker: $marker" ;;
    esac
    return
  fi

  case "$marker" in
    CHECKOUT_BASH_EXEC_ROOT_DELEGATE)
      printf '%scheckout_bash_v1_bind "$checkout_root/$checkout_delegate" ||\n' "$indent"
      printf '%s  die "cannot bind checkout runtime: $checkout_root/$checkout_delegate"\n' "$indent"
      printf '%sexec "$CHECKOUT_BASH_V1_INTERPRETER" "$CHECKOUT_BASH_V1_RUNTIME" "$@"\n' "$indent"
      ;;
    CHECKOUT_BASH_RUN_ROOT_DELEGATE)
      printf '%scheckout_bash_v1_bind "$checkout_root/$checkout_delegate" ||\n' "$indent"
      printf '%s  die "cannot bind checkout runtime: $checkout_root/$checkout_delegate"\n' "$indent"
      printf '%s"$CHECKOUT_BASH_V1_INTERPRETER" "$CHECKOUT_BASH_V1_RUNTIME" "$@" <&0 &\n' "$indent"
      ;;
    CHECKOUT_BASH_EXEC_ROOT_POST)
      printf '%scheckout_bash_v1_bind "$checkout_root/$checkout_post_install_delegate" ||\n' "$indent"
      printf '%s  die "cannot bind checkout runtime: $checkout_root/$checkout_post_install_delegate"\n' "$indent"
      printf '%sexec "$CHECKOUT_BASH_V1_INTERPRETER" "$CHECKOUT_BASH_V1_RUNTIME" "$@"\n' "$indent"
      ;;
    CHECKOUT_BASH_RUN_DIR_DELEGATE)
      printf '%scheckout_bash_v1_bind "%s/$checkout_delegate" ||\n' \
        "$indent" "$managed_root"
      printf '%s  die "cannot bind checkout runtime: %s/$checkout_delegate"\n' \
        "$indent" "$managed_root"
      printf '%s"$CHECKOUT_BASH_V1_INTERPRETER" "$CHECKOUT_BASH_V1_RUNTIME" "$@" <&0 &\n' "$indent"
      ;;
    CHECKOUT_BASH_EXEC_DIR_POST)
      printf '%scheckout_bash_v1_bind "%s/$checkout_post_install_delegate" ||\n' \
        "$indent" "$managed_root"
      printf '%s  die "cannot bind checkout runtime: %s/$checkout_post_install_delegate"\n' \
        "$indent" "$managed_root"
      printf '%sexec "$CHECKOUT_BASH_V1_INTERPRETER" "$CHECKOUT_BASH_V1_RUNTIME" "$@"\n' "$indent"
      ;;
    *) die "unknown Bash invocation marker: $marker" ;;
  esac
}

template_block=
template_block_enabled=true
while IFS= read -r line || [[ -n "$line" ]]; do
  marker_line=${line#"${line%%[![:space:]]*}"}
  case "$marker_line" in
    '# @CHECKOUT_POST_INSTALL_BEGIN@')
      [[ -z "$template_block" ]] ||
        die 'installer template contains a nested conditional block'
      template_block=post-install
      [[ -n "$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE" ]] &&
        template_block_enabled=true || template_block_enabled=false
      continue
      ;;
    '# @CHECKOUT_POST_INSTALL_END@')
      [[ "$template_block" == post-install ]] ||
        die 'installer template closes the wrong post-install block'
      template_block=
      template_block_enabled=true
      continue
      ;;
    '# @CHECKOUT_LOCK_V1_BEGIN@')
      [[ -z "$template_block" ]] ||
        die 'installer template contains a nested conditional block'
      template_block=lock-v1
      [[ "$CHECKOUT_INSTALLER_LOCK_PROTOCOL" == v1 ]] &&
        template_block_enabled=true || template_block_enabled=false
      continue
      ;;
    '# @CHECKOUT_LOCK_V1_END@')
      [[ "$template_block" == lock-v1 ]] ||
        die 'installer template closes the wrong lock-v1 block'
      template_block=
      template_block_enabled=true
      continue
      ;;
    '# @CHECKOUT_LEGACY_LOCK_BEGIN@')
      [[ -z "$template_block" ]] ||
        die 'installer template contains a nested conditional block'
      template_block=legacy-lock
      [[ -z "$CHECKOUT_INSTALLER_LOCK_PROTOCOL" ]] &&
        template_block_enabled=true || template_block_enabled=false
      continue
      ;;
    '# @CHECKOUT_LEGACY_LOCK_END@')
      [[ "$template_block" == legacy-lock ]] ||
        die 'installer template closes the wrong legacy-lock block'
      template_block=
      template_block_enabled=true
      continue
      ;;
    '# @CHECKOUT_LOCK_V1_LIBRARY@')
      [[ "$template_block" == lock-v1 ]] ||
        die 'checkout lock v1 library marker is outside its conditional block'
      if [[ "$template_block_enabled" == true ]]; then
        [[ -f "$lock_v1_fragment" && ! -L "$lock_v1_fragment" ]] ||
          die "checkout lock v1 fragment must be a regular file: $lock_v1_fragment"
        while IFS= read -r fragment_line || [[ -n "$fragment_line" ]]; do
          printf '%s\n' "$fragment_line" >>"$tmp"
        done <"$lock_v1_fragment"
      fi
      continue
      ;;
    '# @CHECKOUT_BASH_RESOLVER_BEGIN@')
      [[ -z "$template_block" ]] ||
        die 'installer template contains a nested conditional block'
      template_block=bash-resolver
      [[ "$CHECKOUT_INSTALLER_BASH_RESOLVER" == v1 ]] &&
        template_block_enabled=true || template_block_enabled=false
      continue
      ;;
    '# @CHECKOUT_BASH_RESOLVER_END@')
      [[ "$template_block" == bash-resolver ]] ||
        die 'installer template closes the wrong Bash resolver block'
      template_block=
      template_block_enabled=true
      continue
      ;;
    '# @CHECKOUT_BASH_RESOLVER_LIBRARY@')
      [[ "$template_block" == bash-resolver ]] ||
        die 'checkout Bash resolver marker is outside its conditional block'
      if [[ "$template_block_enabled" == true ]]; then
        while IFS= read -r fragment_line || [[ -n "$fragment_line" ]]; do
          printf '%s\n' "$fragment_line" >>"$tmp"
        done <"$bash_resolver_fragment"
      fi
      continue
      ;;
    '# @CHECKOUT_DEVELOPMENT_BEGIN@')
      [[ -z "$template_block" ]] ||
        die 'installer template contains a nested conditional block'
      template_block=development
      [[ "$CHECKOUT_INSTALLER_DEVELOPMENT_POLICY" == shdeps ]] &&
        template_block_enabled=true || template_block_enabled=false
      continue
      ;;
    '# @CHECKOUT_DEVELOPMENT_END@')
      [[ "$template_block" == development ]] ||
        die 'installer template closes the wrong development block'
      template_block=
      template_block_enabled=true
      continue
      ;;
    *' # @CHECKOUT_MANAGED_DESTINATION_IF@')
      [[ -z "$template_block" ]] ||
        die 'managed destination marker is inside a conditional block'
      if [[ "$CHECKOUT_INSTALLER_DEVELOPMENT_POLICY" == shdeps ]]; then
        # shellcheck disable=SC2016 # Literal generated shell source.
        printf '%s\n' \
          '  if [[ "$development_checkout_selected" == true ]]; then' \
          '    :' \
          '  elif [[ "$development_checkout_recovered" == true ]]; then' \
          '    validate_managed_checkout "$checkout_dir"' \
          '    require_tracked_delegate "$checkout_dir"' >>"$tmp"
        if [[ -n "$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE" ]]; then
          # shellcheck disable=SC2016 # Literal generated shell source.
          printf '%s\n' \
            '    require_tracked_post_install_delegate "$checkout_dir"' >>"$tmp"
        fi
        # shellcheck disable=SC2016 # Literal generated shell source.
        printf '%s\n' \
          '  elif [[ -e "$checkout_dir" || -L "$checkout_dir" ]]; then' >>"$tmp"
      else
        # shellcheck disable=SC2016 # Literal generated shell source.
        printf '%s\n' \
          '  if [[ -e "$checkout_dir" || -L "$checkout_dir" ]]; then' >>"$tmp"
      fi
      continue
      ;;
    '# @CHECKOUT_DEVELOPMENT_REVALIDATE@')
      if [[ "$CHECKOUT_INSTALLER_DEVELOPMENT_POLICY" == shdeps &&
        (-z "$template_block" || "$template_block_enabled" == true) ]]; then
        invocation_indent=${line%%#*}
        printf '%srevalidate_selected_development_checkout\n' \
          "$invocation_indent" >>"$tmp"
      fi
      continue
      ;;
    '# @CHECKOUT_BASH_EXEC_ROOT_DELEGATE@' | '# @CHECKOUT_BASH_RUN_ROOT_DELEGATE@' | '# @CHECKOUT_BASH_EXEC_ROOT_POST@' | '# @CHECKOUT_BASH_RUN_DIR_DELEGATE@' | '# @CHECKOUT_BASH_EXEC_DIR_POST@')
      if [[ -z "$template_block" || "$template_block_enabled" == true ]]; then
        invocation_marker=${marker_line#\# @}
        invocation_marker=${invocation_marker%@}
        invocation_indent=${line%%#*}
        emit_bash_invocation "$invocation_marker" "$invocation_indent" >>"$tmp"
      fi
      continue
      ;;
  esac
  if [[ -n "$template_block" && "$template_block_enabled" != true ]]; then
    continue
  fi
  line=${line//@CHECKOUT_REPO@/$CHECKOUT_INSTALLER_REPO}
  line=${line//@CHECKOUT_SLUG@/$checkout_slug}
  line=${line//@CHECKOUT_REF@/$CHECKOUT_INSTALLER_REF}
  line=${line//@CHECKOUT_DELEGATE@/$CHECKOUT_INSTALLER_DELEGATE}
  line=${line//@CHECKOUT_DEFAULT_DESTINATION@/$CHECKOUT_INSTALLER_DEFAULT_DESTINATION}
  line=${line//@CHECKOUT_POST_INSTALL_DELEGATE@/$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE}
  line=${line//@CHECKOUT_DEVELOPMENT_POLICY@/$CHECKOUT_INSTALLER_DEVELOPMENT_POLICY}
  if [[ "$CHECKOUT_INSTALLER_DEVELOPMENT_POLICY" == shdeps ]]; then
    line=${line//@CHECKOUT_RUNTIME_ROOT@/\$checkout_runtime_root}
  else
    line=${line//@CHECKOUT_RUNTIME_ROOT@/\$checkout_dir}
  fi
  printf '%s\n' "$line" >>"$tmp"
done <"$template"
[[ -z "$template_block" ]] ||
  die "installer template contains an unterminated $template_block block"

if grep -Eq '@[A-Z][A-Z0-9_]*@' "$tmp"; then
  die 'installer template contains an unresolved token'
fi

chmod 0755 "$tmp"
if [[ "$check" == true ]]; then
  [[ -f "$output" && ! -L "$output" && -x "$output" ]] ||
    die "generated installer must be a regular executable: $output"
  if git -C "$consumer" rev-parse --show-toplevel >/dev/null 2>&1; then
    git -C "$consumer" ls-files --error-unmatch install.sh >/dev/null 2>&1 ||
      die "generated installer is not tracked: $output"
    git -C "$consumer" ls-files --error-unmatch -- \
      "$CHECKOUT_INSTALLER_DELEGATE" >/dev/null 2>&1 ||
      die "checkout installer delegate is not tracked: $delegate"
    if [[ -n "$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE" ]]; then
      git -C "$consumer" ls-files --error-unmatch -- \
        "$CHECKOUT_INSTALLER_POST_INSTALL_DELEGATE" >/dev/null 2>&1 ||
        die "checkout installer post-install command is not tracked: $post_install"
    fi
    if [[ "$CHECKOUT_INSTALLER_BASH_RESOLVER" == v1 ]]; then
      [[ -f "$bash_resolver_output" && ! -L "$bash_resolver_output" ]] ||
        die "generated Bash resolver must be a regular file: $bash_resolver_output"
      git -C "$consumer" ls-files --error-unmatch -- \
        support/checkout-bash-v1.sh >/dev/null 2>&1 ||
        die "generated Bash resolver is not tracked: $bash_resolver_output"
    fi
  fi
  # Git is already part of the checkout-installer contract. Its no-index diff
  # keeps drift verification exact without adding a hidden diffutils/cmp
  # dependency on minimal Arch, Fedora, or Alpine environments.
  if ! command git diff --no-index --quiet --no-ext-diff --no-textconv -- \
    "$tmp" "$output"; then
    die "generated installer differs; run checkout-installer/render.sh $consumer"
  fi
  if [[ "$CHECKOUT_INSTALLER_BASH_RESOLVER" == v1 ]] &&
    ! command git diff --no-index --quiet --no-ext-diff --no-textconv -- \
      "$bash_resolver_tmp" "$bash_resolver_output"; then
    die "generated Bash resolver differs; run checkout-installer/render.sh $consumer"
  fi
  bash_resolver_parent=$(bash_resolver_parent_kind)
  if [[ -z "$CHECKOUT_INSTALLER_BASH_RESOLVER" &&
    "$bash_resolver_parent" == directory &&
    -f "$bash_resolver_output" && ! -L "$bash_resolver_output" &&
    $(sed -n '2p' "$bash_resolver_output") == "$bash_resolver_header" ]]; then
    die "generated Bash resolver remains while resolver policy is disabled: $bash_resolver_output"
  fi
  cleanup_render_temps
  tmp=
  bash_resolver_tmp=
  trap - EXIT
  printf 'checkout-installer-render: verified %s\n' "$output"
  exit 0
fi

verify_generated_publication() {
  local destination=$1 expected_hash=$2 temporary_name=$3 description=$4
  local nested=$destination/$temporary_name

  if [[ -f "$destination" && ! -L "$destination" ]] &&
    [[ $(command git hash-object "$destination" 2>/dev/null) == "$expected_hash" ]]; then
    return 0
  fi
  # POSIX mv treats a late directory as a container. Remove only the exact
  # generated child whose bytes match this publication attempt; never recurse
  # into or otherwise modify the foreign canonical object.
  if [[ -f "$nested" && ! -L "$nested" ]] &&
    [[ $(command git hash-object "$nested" 2>/dev/null) == "$expected_hash" ]]; then
    rm -f "$nested"
  fi
  die "$description did not publish as the canonical regular file: $destination"
}

publish_generated_file() {
  local staged=$1 destination=$2 replace_owned=$3 description=$4

  if [[ "$replace_owned" == true ]]; then
    mv "$staged" "$destination"
  else
    # A same-directory hard link is the portable no-clobber publication path.
    # A late regular file makes ln fail. A late directory may receive a nested
    # link, which the mandatory canonical-result verification removes safely.
    # Android filesystems can reject hard links even within one directory, so
    # fall back to the supported platforms' no-clobber move. A late regular
    # file leaves the stage in place; a late directory can only receive that
    # exact stage name, which the same verification path recognizes.
    if ! ln "$staged" "$destination"; then
      [[ ! -e "$destination" && ! -L "$destination" ]] ||
        die "$description destination appeared before publication: $destination"
      mv -n "$staged" "$destination" ||
        die "cannot publish $description: $destination"
      [[ ! -e "$staged" && ! -L "$staged" ]] ||
        die "$description destination appeared before publication: $destination"
      return 0
    fi
    rm -f "$staged"
  fi
}

installer_hash=$(command git hash-object "$tmp")
installer_tmp_name=${tmp##*/}
if [[ "$CHECKOUT_INSTALLER_BASH_RESOLVER" == v1 ]]; then
  # Publish the optional library before the installer that depends on it. A
  # failure or interruption between these renames leaves the old installer
  # runnable and a harmless newer library; rerendering converges the pair.
  bash_resolver_hash=$(command git hash-object "$bash_resolver_tmp")
  bash_resolver_tmp_name=${bash_resolver_tmp##*/}
  publish_generated_file "$bash_resolver_tmp" "$bash_resolver_output" \
    "$bash_resolver_output_owned" 'generated Bash resolver'
  bash_resolver_tmp=
  verify_generated_publication "$bash_resolver_output" \
    "$bash_resolver_hash" "$bash_resolver_tmp_name" \
    'generated Bash resolver'
  publish_generated_file "$tmp" "$output" "$output_owned" \
    'generated installer'
  tmp=
  verify_generated_publication "$output" "$installer_hash" \
    "$installer_tmp_name" 'generated installer'
else
  # Disabling the resolver takes the inverse safe order: first publish the
  # installer that no longer depends on the library, then retire only an exact
  # generated artifact beneath a real consumer-owned support directory.
  publish_generated_file "$tmp" "$output" "$output_owned" \
    'generated installer'
  tmp=
  verify_generated_publication "$output" "$installer_hash" \
    "$installer_tmp_name" 'generated installer'
  bash_resolver_parent=$(bash_resolver_parent_kind)
  if [[ "$bash_resolver_parent" == directory &&
    -f "$bash_resolver_output" && ! -L "$bash_resolver_output" &&
    $(sed -n '2p' "$bash_resolver_output") == "$bash_resolver_header" ]]; then
    rm -f "$bash_resolver_output"
  fi
fi
trap - EXIT
printf 'checkout-installer-render: %s\n' "$output"
